"""Run a typed public image manifest through reconstruction, voxelization, and LBM."""

from __future__ import annotations

import argparse
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from app.recon.public_evaluation import evaluate_public_dataset


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("manifest", help="CSV generated by prepare_pix3d_manifest.py")
    parser.add_argument("--output-dir", required=True)
    parser.add_argument("--engine", choices=["auto", "sf3d", "depth_anything", "opencv"], default="auto")
    parser.add_argument("--device", choices=["cpu", "cuda"], default=None)
    args = parser.parse_args()
    summary = evaluate_public_dataset(args.manifest, args.output_dir, args.engine, args.device)
    print(
        f"dataset={summary['dataset']} engine={summary['engine_selected']} "
        f"succeeded={summary['n_succeeded']} failed={summary['n_failed']} "
        f"LBM={summary['n_lbm_completed']}/{summary['n_cases']}"
    )
    return 0 if summary["n_failed"] == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
